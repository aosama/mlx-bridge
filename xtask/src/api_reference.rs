//! Generates `docs/reference/` from the crate's doc comments, and audits that the
//! pages are current and that every guide's examples run. The reference exists
//! because documentation indexers such as Context7 read Markdown rather than Rust,
//! and because generation is the only way 700 entries stay true to the code.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;
use std::process::ExitCode;

use crate::repository::{self, collect_rust_sources};
use crate::rust_item_parsing::{
    PublicItem, exported_names_text, module_summary_of, public_items_in_source,
};

const GUIDES_DIRECTORY: &str = "docs";
const REFERENCE_DIRECTORY: &str = "docs/reference";
const GENERATED_NOTICE: &str = "<!-- Generated by `cargo xtask generate-api-reference` from the doc comments in `src/`. Edit those comments, not this file. -->";

/// One source file's contribution to a reference page.
struct ReferenceSection {
    source_path: String,
    module_summary: String,
    public_items: Vec<PublicItem>,
}

/// The page a source file belongs to, chosen by the job the code does.
fn page_for_source(relative_source_path: &str) -> &'static str {
    if relative_source_path.starts_with("operations") {
        "operations"
    } else if relative_source_path.starts_with("compile") {
        "compile-and-transforms"
    } else if relative_source_path.starts_with("metal") {
        "metal"
    } else if relative_source_path.starts_with("runtime") {
        "runtime"
    } else if relative_source_path.starts_with("types") {
        "types"
    } else {
        "context-and-errors"
    }
}

fn page_title(page_name: &str) -> &'static str {
    match page_name {
        "operations" => "Operations reference",
        "compile-and-transforms" => "Compile and transforms reference",
        "metal" => "Metal reference",
        "runtime" => "Runtime reference",
        "types" => "Types reference",
        _ => "Context and errors reference",
    }
}

fn render_page(page_name: &str, sections: &[ReferenceSection]) -> String {
    let mut page = format!("# {}\n\n{GENERATED_NOTICE}\n", page_title(page_name));
    for section in sections {
        page.push_str(&format!("\n## `{}`\n", section.source_path));
        if !section.module_summary.is_empty() {
            page.push_str(&format!("\n{}\n", section.module_summary));
        }
        for public_item in &section.public_items {
            page.push_str(&format!(
                "\n### `{}`\n\n```rust\n{}\n```\n",
                public_item.title, public_item.declaration
            ));
            if !public_item.documentation.is_empty() {
                page.push_str(&format!("\n{}\n", public_item.documentation));
            }
        }
    }
    page
}

/// Renders every page from the sources, or names what stops that: unreadable files
/// or items missing documentation.
fn render_reference(repository_root: &Path) -> Result<BTreeMap<String, String>, Vec<String>> {
    let source_root = repository_root.join("src");
    let mut source_paths = Vec::new();
    if let Err(read_error) = collect_rust_sources(&source_root, &mut source_paths) {
        return Err(vec![format!("cannot read src: {read_error}")]);
    }
    source_paths.sort();
    let crate_root_source = match std::fs::read_to_string(source_root.join("lib.rs")) {
        Ok(crate_root_source) => crate_root_source,
        Err(read_error) => return Err(vec![format!("cannot read src/lib.rs: {read_error}")]),
    };
    let exported_names = exported_names_text(&crate_root_source);
    let mut undocumented_items = Vec::new();
    let mut page_sections: BTreeMap<&str, Vec<ReferenceSection>> = BTreeMap::new();
    for source_path in &source_paths {
        let Ok(relative_path) = source_path.strip_prefix(&source_root) else {
            continue;
        };
        let relative_path = relative_path.to_string_lossy().into_owned();
        // `raw` is generated declarations, documented by the headers it mirrors.
        if relative_path == "raw.rs" || relative_path == "lib.rs" {
            continue;
        }
        let source_text = match std::fs::read_to_string(source_path) {
            Ok(source_text) => source_text,
            Err(read_error) => {
                return Err(vec![format!("cannot read {relative_path}: {read_error}")]);
            }
        };
        let public_items = public_items_in_source(
            &source_text,
            &relative_path,
            &exported_names,
            &mut undocumented_items,
        );
        if !public_items.is_empty() {
            page_sections
                .entry(page_for_source(&relative_path))
                .or_default()
                .push(ReferenceSection {
                    source_path: format!("src/{relative_path}"),
                    module_summary: module_summary_of(&source_text),
                    public_items,
                });
        }
    }
    if !undocumented_items.is_empty() {
        return Err(undocumented_items);
    }
    let mut rendered_pages = BTreeMap::new();
    for (page_name, sections) in &page_sections {
        rendered_pages.insert(format!("{page_name}.md"), render_page(page_name, sections));
    }
    Ok(rendered_pages)
}

fn markdown_files_in(directory: &Path) -> Vec<String> {
    let mut file_names = Vec::new();
    let Ok(directory_entries) = std::fs::read_dir(directory) else {
        return file_names;
    };
    for directory_entry in directory_entries.flatten() {
        let file_name = directory_entry.file_name().to_string_lossy().into_owned();
        if file_name.ends_with(".md") {
            file_names.push(file_name);
        }
    }
    file_names.sort();
    file_names
}

/// Pages whose contents differ from the render, and pages nothing generates anymore.
fn reference_problems(
    existing_pages: &BTreeMap<String, String>,
    rendered_pages: &BTreeMap<String, String>,
) -> Vec<String> {
    let mut problems = Vec::new();
    for (page_file_name, rendered_page) in rendered_pages {
        if existing_pages.get(page_file_name) != Some(rendered_page) {
            problems.push(format!("STALE: {page_file_name}"));
        }
    }
    for page_file_name in existing_pages.keys() {
        if !rendered_pages.contains_key(page_file_name) {
            problems.push(format!("ORPHAN: {page_file_name}"));
        }
    }
    problems
}

fn existing_reference_pages(repository_root: &Path) -> BTreeMap<String, String> {
    let reference_root = repository_root.join(REFERENCE_DIRECTORY);
    let mut existing_pages = BTreeMap::new();
    for page_file_name in markdown_files_in(&reference_root) {
        if let Ok(page_text) = std::fs::read_to_string(reference_root.join(&page_file_name)) {
            existing_pages.insert(page_file_name, page_text);
        }
    }
    existing_pages
}

/// Guides with Rust examples that `src/lib.rs` does not attach, whose examples would
/// otherwise silently never run while the guides promise they do.
fn unattached_guides(
    guide_texts: &BTreeMap<String, String>,
    crate_root_source: &str,
) -> Vec<String> {
    let mut attached_guides = BTreeSet::new();
    for source_line in crate_root_source.lines() {
        if let Some(after_prefix) = source_line.split("include_str!(\"../docs/").nth(1)
            && let Some((guide_file_name, _)) = after_prefix.split_once('"')
        {
            attached_guides.insert(guide_file_name.to_owned());
        }
    }
    let mut unattached_guide_names = Vec::new();
    for (guide_file_name, guide_text) in guide_texts {
        if guide_text.contains("```rust") && !attached_guides.contains(guide_file_name) {
            unattached_guide_names.push(guide_file_name.clone());
        }
    }
    unattached_guide_names
}

fn guide_texts_in(repository_root: &Path) -> BTreeMap<String, String> {
    let guides_root = repository_root.join(GUIDES_DIRECTORY);
    let mut guide_texts = BTreeMap::new();
    for guide_file_name in markdown_files_in(&guides_root) {
        if let Ok(guide_text) = std::fs::read_to_string(guides_root.join(&guide_file_name)) {
            guide_texts.insert(guide_file_name, guide_text);
        }
    }
    guide_texts
}

/// The verify and continuous-integration leg: every public item is documented, the
/// pages are current, and every guide's examples are attached so they run.
pub(crate) fn audit_documentation(repository_root: &Path) -> bool {
    let rendered_pages = match render_reference(repository_root) {
        Ok(rendered_pages) => rendered_pages,
        Err(render_problems) => {
            for render_problem in &render_problems {
                eprintln!("[reference]   NO DOC COMMENT OR UNREADABLE: {render_problem}");
            }
            return false;
        }
    };
    let page_problems =
        reference_problems(&existing_reference_pages(repository_root), &rendered_pages);
    for page_problem in &page_problems {
        eprintln!("[reference]   {page_problem}; run cargo xtask generate-api-reference");
    }
    let crate_root_source =
        std::fs::read_to_string(repository_root.join("src/lib.rs")).unwrap_or_default();
    let unattached_guide_names =
        unattached_guides(&guide_texts_in(repository_root), &crate_root_source);
    for guide_file_name in &unattached_guide_names {
        eprintln!(
            "[reference]   UNATTACHED: docs/{guide_file_name} has examples src/lib.rs does not run"
        );
    }
    page_problems.is_empty() && unattached_guide_names.is_empty()
}

/// Writes the pages and removes any page nothing generates anymore, so the directory
/// holds exactly what the sources describe.
fn write_reference(repository_root: &Path) -> Result<(), String> {
    let rendered_pages = match render_reference(repository_root) {
        Ok(rendered_pages) => rendered_pages,
        Err(render_problems) => return Err(render_problems.join("\n")),
    };
    let reference_root = repository_root.join(REFERENCE_DIRECTORY);
    if let Err(create_error) = std::fs::create_dir_all(&reference_root) {
        return Err(create_error.to_string());
    }
    for page_file_name in markdown_files_in(&reference_root) {
        if !rendered_pages.contains_key(&page_file_name) {
            if let Err(remove_error) = std::fs::remove_file(reference_root.join(&page_file_name)) {
                return Err(remove_error.to_string());
            }
            println!("[reference] removed {REFERENCE_DIRECTORY}/{page_file_name}");
        }
    }
    for (page_file_name, rendered_page) in &rendered_pages {
        if let Err(write_error) = std::fs::write(reference_root.join(page_file_name), rendered_page)
        {
            return Err(write_error.to_string());
        }
        println!("[reference] wrote {REFERENCE_DIRECTORY}/{page_file_name}");
    }
    Ok(())
}

/// `cargo xtask generate-api-reference [--check]`.
pub fn run(arguments: &[String]) -> ExitCode {
    let repository_root = repository::repository_root();
    if arguments.first().map(String::as_str) == Some("--check") {
        if audit_documentation(&repository_root) {
            println!("[reference] documentation audit: PASS");
            return ExitCode::SUCCESS;
        }
        return ExitCode::FAILURE;
    }
    match write_reference(&repository_root) {
        Ok(()) => ExitCode::SUCCESS,
        Err(write_problem) => {
            eprintln!("[reference] {write_problem}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pages(page_entries: &[(&str, &str)]) -> BTreeMap<String, String> {
        let mut page_map = BTreeMap::new();
        for (page_file_name, page_text) in page_entries {
            page_map.insert((*page_file_name).to_owned(), (*page_text).to_owned());
        }
        page_map
    }

    #[test]
    fn should_report_nothing_when_pages_match_the_render() {
        let rendered = pages(&[("types.md", "same")]);

        assert!(reference_problems(&rendered, &rendered).is_empty());
    }

    #[test]
    fn should_report_a_changed_and_a_missing_page_as_stale() {
        let existing = pages(&[("types.md", "old")]);
        let rendered = pages(&[("types.md", "new"), ("metal.md", "new")]);

        assert_eq!(
            reference_problems(&existing, &rendered),
            vec!["STALE: metal.md", "STALE: types.md"]
        );
    }

    #[test]
    fn should_report_a_page_nothing_generates_as_an_orphan() {
        let existing = pages(&[("retired.md", "old")]);

        assert_eq!(
            reference_problems(&existing, &BTreeMap::new()),
            vec!["ORPHAN: retired.md"]
        );
    }

    #[test]
    fn should_flag_a_guide_with_examples_that_nothing_attaches() {
        let guides = pages(&[
            ("attached.md", "```rust\n```"),
            ("forgotten.md", "```rust\n```"),
        ]);

        let unattached =
            unattached_guides(&guides, "#[doc = include_str!(\"../docs/attached.md\")]");

        assert_eq!(unattached, vec!["forgotten.md"]);
    }

    #[test]
    fn should_not_require_attaching_a_guide_without_rust_examples() {
        let guides = pages(&[("prose.md", "Only words.\n\n```bash\nls\n```")]);

        assert!(unattached_guides(&guides, "").is_empty());
    }

    #[test]
    fn should_choose_a_page_by_source_family_with_a_fallback() {
        assert_eq!(page_for_source("operations/fft.rs"), "operations");
        assert_eq!(page_for_source("types/array.rs"), "types");
        assert_eq!(page_for_source("error.rs"), "context-and-errors");
    }

    #[test]
    fn should_render_a_page_with_its_heading_notice_and_entries() {
        let sections = [ReferenceSection {
            source_path: "src/sample.rs".to_owned(),
            module_summary: "A summary.".to_owned(),
            public_items: vec![PublicItem {
                title: "Sample::read".to_owned(),
                declaration: "pub fn read(&self)".to_owned(),
                documentation: "Reads it.".to_owned(),
            }],
        }];

        let page = render_page("types", &sections);

        assert!(page.starts_with("# Types reference\n"), "{page}");
        assert!(page.contains(GENERATED_NOTICE), "{page}");
        assert!(page.contains("## `src/sample.rs`\n\nA summary."), "{page}");
        assert!(
            page.contains("### `Sample::read`\n\n```rust\npub fn read(&self)\n```\n\nReads it."),
            "{page}"
        );
    }
}
