//! Completes an installed MLX prefix with what MLX's own install omits.

use std::path::Path;

const GGUF_ARCHIVE_FILE_NAME: &str = "libgguflib.a";

/// Reports whether `prefix/lib` holds MLX's GGUF archive. MLX makes GGUF
/// support optional, so a prefix the consumer built may omit it.
pub fn prefix_carries_gguf_archive(prefix: &Path) -> bool {
    prefix.join("lib").join(GGUF_ARCHIVE_FILE_NAME).is_file()
}

/// Installs the pieces the MLX-C build and static consumers need. Idempotent,
/// so a resumed build that skips the MLX phase still completes the prefix.
///
/// # Errors
/// Names the piece that could not be installed. Failing here, loudly, beats a
/// later bare `find_package(jaccl)` or undefined-symbol error that says nothing
/// about the real cause.
pub fn complete_mlx_prefix(mlx_build: &Path, prefix: &Path) -> Result<(), String> {
    install_gguf_archive(mlx_build, prefix).map_err(gguf_install_failure)?;
    write_jaccl_package_config(prefix)
}

fn gguf_install_failure(install_error: std::io::Error) -> String {
    format!("failed to install MLX's GGUF archive into the prefix: {install_error}")
}

/// MLX builds the archive, but its install rule omits it because a shared
/// libmlx absorbs it; a static consumer must link it directly.
fn install_gguf_archive(mlx_build: &Path, prefix: &Path) -> std::io::Result<()> {
    if prefix_carries_gguf_archive(prefix) {
        return Ok(());
    }
    let built_archive = mlx_build.join("mlx/io").join(GGUF_ARCHIVE_FILE_NAME);
    std::fs::copy(
        built_archive,
        prefix.join("lib").join(GGUF_ARCHIVE_FILE_NAME),
    )?;
    Ok(())
}

/// MLX's install ships jaccl's imported targets without the package config
/// `find_package(jaccl)` needs: upstream consumes jaccl internally and never
/// expected it found as a package, which surfaces exactly when a consumer (the
/// MLX-C build, through the forward edit set) takes the system-MLX path. This
/// writes the standard minimal config, and stands down the day an MLX install
/// ships its own.
fn write_jaccl_package_config(prefix: &Path) -> Result<(), String> {
    let config_directory = prefix.join("lib/cmake/jaccl");
    let config_path = config_directory.join("jacclConfig.cmake");
    if !config_directory.join("jacclTargets.cmake").is_file() || config_path.is_file() {
        return Ok(());
    }
    let package_config = "# Generated by the mlx-c-rust native build engine: MLX's install\n\
         # ships jaccl's targets without the package config that\n\
         # find_package(jaccl) searches for. Completing the packaging.\n\
         if(NOT TARGET jaccl::jaccl)\n\
           include(\"${CMAKE_CURRENT_LIST_DIR}/jacclTargets.cmake\")\n\
         endif()\n";
    if let Err(config_write_error) = std::fs::write(&config_path, package_config) {
        return Err(format!(
            "could not write the generated jaccl package config at {}: {config_write_error}; \
             the MLX-C configure will fail to find jaccl",
            config_path.display()
        ));
    }
    Ok(())
}
